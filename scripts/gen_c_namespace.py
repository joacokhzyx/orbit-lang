#!/usr/bin/env python3
"""Generate compiler/front/c_namespace.orb from the runtime's C names.

The emitted C translator unit includes `runtime.h`, and a user function is
emitted under its own name. Naming one after a runtime export is therefore a
second declaration of that symbol, and the C compiler rejects the program with
"conflicting types" after `orbit check` accepted it. The list of runtime names
used to be nobody's job, so it drifted: `system_uptime` and the `ORBIT_*`
macros were never reserved.

This script makes the runtime half the runtime's own text. It reads
`runtime/*.h`, `runtime/database.c` and `runtime/auth.c`, extracts the names
the runtime declares or defines, and writes them as one predicate that
`compiler/front/sema.orb` calls. Adding an export to the runtime and forgetting
to reserve it is then a stale table, which `--check` reports.

The libc half stays curated in `sema.orb`. Those names come from the build
host's headers, not from this tree, and a table generated from the host would
accept a program on Linux and refuse it on Windows.

Usage:
    python scripts/gen_c_namespace.py            # write the table
    python scripts/gen_c_namespace.py --check    # fail if it is stale
    python scripts/gen_c_namespace.py --self-test

`--self-test` is hermetic: it drives the extractor and the staleness check on
synthetic sources, and asserts a comment or a string that looks like a call is
not collected.
"""

import argparse
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
RUNTIME = ROOT / "runtime"
TARGET = ROOT / "compiler" / "front" / "c_namespace.orb"

# A name followed by the opening parenthesis of a declaration, definition or
# call. The three prefixes are the three classes the runtime owns: exported
# functions, the system_* telemetry exports, and the function-like macros.
NAME_RE = re.compile(r"\b((?:orbit_|system_|ORBIT_)[A-Za-z0-9_]+)\s*\(")

# The router switches are macros in the translated unit but no runtime header
# defines them: the compiler emits `#define ORBIT_CUSTOM_ROUTER`, and the
# library build passes -DORBIT_LIB_NO_ROUTER. The runtime only tests both, so a
# scan of its `#ifdef`s cannot tell them from the ORBIT_WITH_* build switches,
# which a user translation unit neither defines nor expands.
ROUTER_MACROS = ("ORBIT_CUSTOM_ROUTER", "ORBIT_LIB_NO_ROUTER")

HEADER = """\
// Generated by scripts/gen_c_namespace.py from runtime/*.h, runtime/database.c
// and runtime/auth.c. Do not edit this file: change the C source and run
// `python scripts/gen_c_namespace.py`.
//
// A user function is emitted under its own name into a translation unit that
// already declares these names, so the C compiler refuses the program after
// `orbit check` accepted it. The libc half is curated in sema.orb instead,
// because those names come from the build host's headers rather than this tree.

fn reservedRuntimeName(name: string) -> bool {
"""

FOOTER = """\
    return false
}
"""


def strip_c(text: str) -> str:
    """Remove comments and string/char literals.

    A name mentioned in prose is not a declaration. Without this, a comment
    that spells `orbit_foo(` reserves a name the runtime does not own.
    """
    out = []
    i = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                i += 1
        elif c == "/" and i + 1 < n and text[i + 1] == "*":
            i += 2
            while i + 1 < n and not (text[i] == "*" and text[i + 1] == "/"):
                i += 1
            i += 2
        elif c == '"' or c == "'":
            quote = c
            i += 1
            while i < n:
                if text[i] == "\\":
                    i += 2
                    continue
                if text[i] == quote:
                    i += 1
                    break
                i += 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def extract(sources) -> set:
    """Every runtime-owned name in the given C source texts."""
    names = set(ROUTER_MACROS)
    for text in sources:
        names.update(NAME_RE.findall(strip_c(text)))
    return names


def render(names) -> str:
    body = "".join('    if name == "%s" { return true }\n' % name
                   for name in sorted(names))
    return HEADER + body + FOOTER


def counts(names) -> str:
    orbit = sum(1 for n in names if n.startswith("orbit_"))
    system = sum(1 for n in names if n.startswith("system_"))
    macro = sum(1 for n in names if n.startswith("ORBIT_"))
    return ("%d names (%d orbit_*, %d system_*, %d ORBIT_*)"
            % (len(names), orbit, system, macro))


def first_difference(expected: str, actual: str):
    """(line, expected line, actual line) for the first disagreement."""
    e = expected.splitlines()
    a = actual.splitlines()
    for i in range(min(len(e), len(a))):
        if e[i] != a[i]:
            return i + 1, e[i], a[i]
    if len(e) != len(a):
        line = min(len(e), len(a)) + 1
        want = e[line - 1] if line <= len(e) else "<end of file>"
        got = a[line - 1] if line <= len(a) else "<end of file>"
        return line, want, got
    return None


def stale_problem(expected: str, actual) -> str:
    """Why the committed table disagrees with the expected text, or ""."""
    if actual is None:
        return "compiler/front/c_namespace.orb is missing"
    if actual == expected:
        return ""
    diff = first_difference(expected, actual)
    if diff is None:
        return "the committed table differs from the generated one"
    line, want, got = diff
    return ("the committed table is stale at line %d\n  generated: %s\n"
            "  committed: %s" % (line, want, got))


def runtime_sources() -> list:
    headers = sorted(RUNTIME.glob("*.h"))
    extra = [RUNTIME / "database.c", RUNTIME / "auth.c"]
    missing = [p for p in extra if not p.exists()]
    if not headers or missing:
        raise FileNotFoundError(
            "runtime sources missing: %s"
            % ", ".join(str(p) for p in ([] if headers else [RUNTIME / "*.h"])
                        + missing))
    return [p.read_text(encoding="utf-8", errors="replace")
            for p in headers + extra]


def self_test() -> int:
    """The extractor and the staleness check must both be able to say no."""
    header = (
        "int orbit_kept(int);\n"
        "/* int orbit_in_comment(int); */\n"
        "static const char* s = \"orbit_in_string(\";\n"
        "// ORBIT_IN_LINE_COMMENT(x)\n"
        "#ifndef ORBIT_ONLY_IN_CONDITION\n"
        "#define ORBIT_ONLY_IN_CONDITION 1\n"
        "#endif\n"
    )
    c_source = (
        "static bool system_fixture(void) { return true; }\n"
        "static bool orbit_fixture_two(void) { return false; }\n"
    )
    names = extract([header, c_source])
    want = {"orbit_kept", "system_fixture", "orbit_fixture_two"} \
        | set(ROUTER_MACROS)
    if names != want:
        print("self-test FAILED: the extractor collected names from comments or "
              "strings, or missed a declaration; it found %s" % sorted(names))
        return 1
    if render(names) != render(set(reversed(sorted(names)))):
        print("self-test FAILED: the table is not deterministic")
        return 1
    if stale_problem(render(names), render(names)) != "":
        print("self-test FAILED: an identical table was reported stale")
        return 1
    with_new = set(names) | {"orbit_fixture_three"}
    if not stale_problem(render(with_new), render(names)):
        print("self-test FAILED: a table missing a runtime name was accepted")
        return 1
    if not stale_problem(render(names), None):
        print("self-test FAILED: a missing table was accepted")
        return 1
    print("Finished c-namespace self-test: 5/5 (comments and strings are "
          "skipped, rendering is deterministic, and a stale or missing table "
          "is reported)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="compare the committed table with the runtime; fail if stale")
    ap.add_argument("--self-test", action="store_true",
                    help="assert the extractor and the staleness check can fail")
    args = ap.parse_args()

    if args.self_test:
        return self_test()

    try:
        names = extract(runtime_sources())
    except FileNotFoundError as exc:
        print("Failed c-namespace: %s" % exc)
        return 2
    if not names:
        print("Failed c-namespace: the runtime sources named no orbit_*, "
              "system_* or ORBIT_* names; the extractor matched nothing")
        return 2

    expected = render(names)
    if args.check:
        try:
            actual = TARGET.read_text(encoding="utf-8")
        except FileNotFoundError:
            actual = None
        problem = stale_problem(expected, actual)
        if problem:
            print("Failed c-namespace: %s\nRun: python scripts/gen_c_namespace.py"
                  % problem)
            return 1
        print("Finished c-namespace: %s match compiler/front/c_namespace.orb"
              % counts(names))
        return 0

    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print("Finished c-namespace: wrote %s with %s" % (TARGET, counts(names)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
