#!/usr/bin/env python3
"""Dual-toolchain judge (carril T2): the corpus must behave byte-identically under tcc and gcc.

Corpus: tests/suite + tests/std (67+22), same discovery as scripts/test_suite.py
(`*.orb` minus `*.support.orb`; `--dir` is repeatable), minus the db-link
exclusions in DUAL_DB_EXCLUDE (2 tests whose link needs the MSVC
sqlite3.lib, which tcc cannot read; the gcc suite still covers them and the
closing line counts them). Every remaining test is built
twice from the same fixed-point compiler -- once with the gcc driver, once
with tcc 0.9.27 -- and both binaries run. The gate requires byte-identical
exit code AND stdout between the two arms. A disagreement is SIGNAL, not
noise: the gate fails and prints the diff (lengths, first differing byte,
both tails). It never resolves by trusting one toolchain.

Verdicts reuse test_suite.py's rules on the agreed result (`// expect-exit N`,
`// known-failing: <ref>` ratchet), so a green dual run implies the same
verdicts a gcc suite run gives, plus agreement. The machinery is imported,
not duplicated: test discovery defaults and the build/run protocol
(`[compiler, build, path, -o, exe]` in cwd=ROOT, per-case TEMP, vendor DLL
PATH, disposable flags) follow test_suite.py and _common.disposable_test_env.

tcc is a correctness judge here, never a benchmark: tcc emits unoptimized
code, so any timing comparison against gcc from these binaries is meaningless
and this script prints none. The multithreaded server is excluded from the
dual corpus by construction: tcc judge builds are single-thread-only (tcc
predefines __TINYC__ and provides no __thread TLS and no __atomic_* builtins,
so the repo shim degrades both to plain operations that race), and the server
stays a gcc build by design -- kynx_gate.py is the server's gate, not this.

The tcc arm carries its toolchain gaps in ORBIT_CCFLAGS_EXTRA, never in the
repo: the carril-T winsock shim (`-I<shim> -include tccenv.h`, local-only,
see --tcc-shim), a generated force-include with plain-op Interlocked64 /
__sync_* macros (linker-level gaps the repo __TINYC__ shim does not cover),
and the system advapi32.dll for RtlGenRandom. The gcc arm builds unity, the
same as a standalone test_suite.py run (ORBIT_LINK_RUNTIME is 0: the
separate-compilation lane is parity_selfhost.py's business, not this judge's).

Usage:
    python scripts/dual_judge.py [--compiler PATH] [--cc GCC] [--tcc TCC]
                                 [--tcc-shim DIR] [--timeout S] [--dir D]...
    python scripts/dual_judge.py --self-test

Exit code 0 iff every test agreed AND every agreed verdict holds.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
import threading
import time
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import orbit_output as out
import _common
import test_suite as suite

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Force-include the tcc arm writes into its own work dir (never the repo).
# Linker-level tcc 0.9.27 gaps the repo __TINYC__ shim does not carry: the
# repo shim (runtime/orbit_api.h and friends) covers __thread and __atomic_*,
# but 64-bit Interlocked* (tcc's winbase.h aliases them to _-prefixed imports
# that exist in no import library) and __sync_* (absent from tcc on every
# platform) still need definitions. Plain single-threaded ops, correct only
# because tcc judge builds never serve concurrent requests (see above); every
# fetch_* use site in this tree discards the return value, matching the
# repo shim's own contract. Included AFTER tccenv.h so its <windows.h> has
# already declared the real names; the #undefs below neutralise tcc's own
# _-prefixed aliases before the use sites expand.
TCC_DUAL_HEADER = """\
/* Generated by scripts/dual_judge.py (scripts/triangle.py writes the same
 * bytes): linker-level tcc 0.9.27 gaps. Single-thread-only plain ops. */
#undef InterlockedIncrement64
#undef InterlockedExchangeAdd64
#undef InterlockedCompareExchange64
#define InterlockedIncrement64(p) (++(*(p)))
#define InterlockedExchangeAdd64(p, v) ((*(p) += (v)) - (v))
#define InterlockedCompareExchange64(p, e, c) (*(p) == (c) ? (*(p) = (e), (c)) : *(p))
#undef __sync_fetch_and_add
#undef __sync_fetch_and_sub
#undef __sync_bool_compare_and_swap
#undef __sync_lock_release
#define __sync_fetch_and_add(ptr, val) ((*(ptr) += (val)) - (val))
#define __sync_fetch_and_sub(ptr, val) ((*(ptr) -= (val)) + (val))
#define __sync_bool_compare_and_swap(ptr, oldv, newv) \\
    (*(ptr) == (oldv) ? (*(ptr) = (newv), 1) : 0)
#define __sync_lock_release(ptr) ((void)(*(ptr) = 0))
"""

# Local-lane convenience only: the carril-T portable, outside the repo.
TCCVAL_TCC = r"C:\Temp\tccval\tcc\tcc\tcc.exe"
TCCVAL_SHIM = r"C:\Temp\tccval\shim"
ADVAPI32 = r"C:\Windows\System32\advapi32.dll"

# Tests the tcc arm cannot link, skipped openly (never silently).
#
# By file stem so --dir prefixing cannot hide them. Today both exercise
# db_* opcodes, so the compiler links runtime/vendor/win-x64/sqlite3.lib;
# tcc 0.9.27 rejects that MSVC import library ("invalid object file") and
# the path is hardcoded in the compiler's cc line, so no flag can reroute
# it to the DLL the way the advapi32 gap is handled above. This is a
# toolchain link limitation, not a semantic disagreement: the gcc suite
# still builds and runs them, and the dual closing line counts them
# separately. A stem added here must name the limitation, not the test.
DUAL_DB_EXCLUDE = {
    # db_* DCE-veto shapes; link sqlite3.lib.
    "arena_sink_scope": "links MSVC sqlite3.lib, unreadable by tcc",
    "peephole_no_fold_side_effects": "links MSVC sqlite3.lib, unreadable by tcc",
}


def resolve_tcc(explicit=None):
    """The tcc driver, or None when there is none to judge with."""
    for cand in (explicit, os.environ.get("ORBIT_TCC")):
        if cand:
            return cand
    found = shutil.which("tcc") or shutil.which("tcc.exe")
    if found:
        return found
    if os.name == "nt" and os.path.isfile(TCCVAL_TCC):
        return TCCVAL_TCC
    return None


def resolve_tcc_shim(explicit=None, tcc_path=None):
    """A winsock shim dir for tcc on Windows, or None.

    Two generations exist: the carril-T local shim (tccenv.h) and the
    versioned repo shim (vendor/tcc-shim/tcc_toolchain.h). Either is
    accepted; which header to -include is decided by shim_header().
    """
    for cand in (explicit, os.environ.get("ORBIT_TCC_SHIM")):
        if cand:
            return cand
    if tcc_path and "tccval" in tcc_path.replace("/", os.sep):
        root = tcc_path.replace("/", os.sep).split("tccval")[0] + "tccval"
        cand = os.path.join(root, "shim")
        if os.path.isdir(cand):
            return cand
    if os.name == "nt" and os.path.isdir(TCCVAL_SHIM):
        return TCCVAL_SHIM
    repo_shim = os.path.join(ROOT, "vendor", "tcc-shim")
    if os.name == "nt" and os.path.isdir(repo_shim):
        return repo_shim
    return None


def shim_header(shimdir):
    """Which -include header a shim dir provides, or None.

    tccenv.h (carril-T local) wins when both exist: it is the header the
    87/87 dual validation ran against; tcc_toolchain.h is the versioned
    equivalent for fresh machines and CI.
    """
    if not shimdir:
        return None
    for header in ("tccenv.h", "tcc_toolchain.h"):
        if os.path.isfile(os.path.join(shimdir, header)):
            return header
    return None


def base_env(work, cc):
    """Child env shared by both arms: test_suite.py's recipe, one addition.

    Same vendor-DLL PATH prepend, same disposable flags; ORBIT_LINK_RUNTIME
    is 0, so both arms judge the unity build even when the ambient
    environment asks for the link lane.
    """
    env = dict(os.environ)
    if os.name == "nt":
        vendordll = os.path.join(ROOT, "runtime", "vendor", "win-x64")
        env["PATH"] = vendordll + os.pathsep + env.get("PATH", "")
    # Each case owns its TEMP: the intermediate C has a fixed name
    # (orbit_selfhost_build.c), so a shared TEMP lets one case's cc read
    # another's half-written C -- the exact race test_suite.py documents.
    env["TEMP"] = str(work)
    env["TMP"] = str(work)
    env["TMPDIR"] = str(work)
    env.update({"ORBIT_CC": cc, "CC": cc})
    env = _common.disposable_test_env(env, cc=cc)
    env["ORBIT_LINK_RUNTIME"] = "0"
    return env


def tcc_extra(shimdir, workshim):
    """ORBIT_CCFLAGS_EXTRA for the tcc arm (replaces, not appends).

    The ambient extra is dropped on purpose: a gcc-only flag there
    (-march=, -pipe is harmless, others may not be) would fail the tcc arm
    for reasons unrelated to the corpus. What stays is exactly the three
    documented gaps: winsock headers, tccenv.h, the generated header, and
    advapi32 for RtlGenRandom.
    """
    parts = []
    if os.name == "nt":
        parts += ['-I"%s"' % shimdir, "-include", shim_header(shimdir) or "tccenv.h"]
    parts += ['-I"%s"' % workshim, "-include", "tcc_dual.h"]
    if os.name == "nt":
        parts += ['"%s"' % ADVAPI32]
    return " ".join(parts)


def compare_probes(gcc_rc, gcc_out, tcc_rc, tcc_out):
    """Agreement check, pure function so --self-test needs no compiler.

    Returns None when the arms agree, else a one-line description of the
    first difference (the SIGNAL this gate exists to report).
    """
    if gcc_rc != tcc_rc:
        return "exit differs: gcc=%d tcc=%d" % (gcc_rc, tcc_rc)
    if gcc_out != tcc_out:
        off = next((i for i, (a, b) in enumerate(zip(gcc_out, tcc_out))
                    if a != b), min(len(gcc_out), len(tcc_out)))
        return ("stdout differs at byte %d (len gcc=%d tcc=%d)" %
                (off, len(gcc_out), len(tcc_out)))
    return None


def diff_detail(gcc_out, tcc_out, limit=3):
    """Human-readable tails around the first stdout difference."""
    off = next((i for i, (a, b) in enumerate(zip(gcc_out, tcc_out))
                if a != b), min(len(gcc_out), len(tcc_out)))
    lines = []
    for tag, buf in (("gcc", gcc_out), ("tcc", tcc_out)):
        tail = buf[max(0, off - 120):off + 120]
        lines.append("  %s[%d:%d]: %r" % (tag, max(0, off - 120),
                                          off + 120, tail[:240]))
        if len(lines) >= limit + 1:
            break
    return lines


def collect_tests(suite_dirs):
    """Same discovery and header rules as test_suite.py (imported, not copied).

    Returns (tests, plans): tests counts every .orb found, plans holds
    (path, name, expected, ratchet_ref) for the runner.
    """
    tests = []
    for suite_dir in suite_dirs:
        if not os.path.isdir(suite_dir):
            return None, "no such directory %s" % suite_dir
        for f in sorted(os.listdir(suite_dir)):
            if f.endswith(".orb") and not f.endswith(".support.orb"):
                tests.append(os.path.join(suite_dir, f))
    plans = []
    skipped = []
    excluded = []
    for path in tests:
        name = os.path.splitext(os.path.basename(path))[0]
        if len(suite_dirs) > 1:
            name = os.path.basename(os.path.dirname(path)) + "/" + name
        stem = os.path.splitext(os.path.basename(path))[0]
        if stem in DUAL_DB_EXCLUDE:
            excluded.append((name, DUAL_DB_EXCLUDE[stem]))
            continue
        src = open(path, encoding="utf-8").read()
        m = re.search(r"^\s*//\s*expect-exit\s+(\d+)", src, re.M)
        ratchet = re.search(r"^\s*//\s*known-failing\s*:?\s*(\S.*?)\s*$",
                            src, re.M)
        if m and ratchet:
            skipped.append((name, "both directives"))
            continue
        expected = None if ratchet else (int(m.group(1)) if m else 0)
        plans.append((path, name, expected,
                      ratchet.group(1) if ratchet else None))
    return tests, (plans, skipped, excluded)


def run_dual_one(plan, ctx):
    """Build + run one test under both drivers. Main thread reports."""
    path, name, _, _ = plan
    gcc, tcc, compiler, timeout = (ctx["gcc"], ctx["tcc"], ctx["compiler"],
                                  ctx["timeout"])
    work = ctx["work"]
    exe_suffix = ".exe" if os.name == "nt" else ""
    safe = name.replace("/", "_")
    probes = {}
    arm_secs = {}
    for tag, drv in (("gcc", gcc), ("tcc", tcc)):
        t_arm = time.monotonic()
        tmp = os.path.join(work, "t_" + safe, tag)
        os.makedirs(tmp, exist_ok=True)
        env = base_env(tmp, drv)
        if tag == "tcc":
            env["ORBIT_CCFLAGS_EXTRA"] = ctx["tcc_extra"]
        out_exe = os.path.join(work, safe + "_" + tag + exe_suffix)
        try:
            proc = subprocess.run(
                [compiler, "build", path, "-o", out_exe],
                cwd=ROOT, env=env, capture_output=True, text=True,
                errors="replace", timeout=timeout)
            build_rc = proc.returncode
        except subprocess.TimeoutExpired:
            return (name, "timeout-build", tag)
        if build_rc != 0 or not os.path.isfile(out_exe):
            diag = ((proc.stderr or "").strip() or
                    (proc.stdout or "").strip())
            tail = "\r\n".join(diag.splitlines()[-8:])
            return (name, "nobuild", tag, tail, build_rc)
        try:
            run = subprocess.run([out_exe], cwd=work, capture_output=True,
                                 timeout=timeout)
        except subprocess.TimeoutExpired:
            return (name, "timeout-run", tag)
        arm_secs[tag] = time.monotonic() - t_arm
        probes[tag] = (run.returncode, run.stdout or b"")
    with ctx["lock"]:
        ctx["arm_secs"]["gcc"] += arm_secs["gcc"]
        ctx["arm_secs"]["tcc"] += arm_secs["tcc"]
    desc = compare_probes(probes["gcc"][0], probes["gcc"][1],
                          probes["tcc"][0], probes["tcc"][1])
    if desc is not None:
        return (name, "disagree", desc, probes["gcc"], probes["tcc"])
    return (name, "agree", probes["gcc"][0], probes["gcc"][1])


def self_test():
    """The comparator without a compiler: each failure class must be caught."""
    cases = [
        ("identical probes agree",
         (0, b"ok\n", 0, b"ok\n"), None),
        ("exit difference is signal",
         (0, b"", 1, b""), "exit differs"),
        ("one stdout byte is signal",
         (0, b"abc", 0, b"abd"), "byte 2"),
        ("empty vs non-empty is signal",
         (0, b"", 0, b"x"), "byte 0"),
        ("length-only difference names the offset",
         (0, b"ab", 0, b"abc"), "byte 2"),
    ]
    passed = 0
    for title, (grc, gout, trc, tout), want in cases:
        got = compare_probes(grc, gout, trc, tout)
        good = (got is None) if want is None else (got and want in got)
        if good:
            passed += 1
            print("  ok    %-42s -> %s" % (title, got or "agree"))
        else:
            out.fail("  WRONG %-39s -> %s (wanted %s)"
                     % (title, got or "agree", want or "agree"))
    out.finish("dual self-test", passed, len(cases))
    return 0 if passed == len(cases) else 1


def main() -> int:
    ap = argparse.ArgumentParser(description="Dual-toolchain judge: tcc vs gcc on the corpus")
    ap.add_argument("--compiler", default=None)
    ap.add_argument("--cc", default=None,
                    help="gcc-side C driver (default: ORBIT_CC/CC/gcc)")
    ap.add_argument("--tcc", default=None,
                    help="tcc driver (default: ORBIT_TCC/which tcc/carril-T portable)")
    ap.add_argument("--tcc-shim", default=None,
                    help="carril-T winsock shim dir (default: ORBIT_TCC_SHIM/beside the portable)")
    ap.add_argument("--timeout", type=int, default=120)
    ap.add_argument("--dir", action="append", default=None)
    ap.add_argument("--workers", type=int, default=None)
    ap.add_argument("--work", default=None)
    ap.add_argument("--keep", action="store_true")
    ap.add_argument("--self-test", action="store_true",
                    help="check the comparator on synthetic probes (no compiler needed)")
    out.add_quiet(ap)
    args = ap.parse_args()
    out.set_quiet(args.quiet)

    if args.self_test:
        return self_test()

    gcc = args.cc or _common.resolve_cc()
    tcc = resolve_tcc(args.tcc)
    if not tcc:
        out.fail("Failed dual: no tcc driver found (pass --tcc PATH, set "
                 "ORBIT_TCC, or put tcc on PATH). gcc-vs-gcc substitution "
                 "validates the logic: --tcc <gcc> must go green.")
        return 2
    substitute = tcc == gcc
    shimdir = None
    if not substitute and os.name == "nt":
        shimdir = resolve_tcc_shim(args.tcc_shim, tcc)
        if not shimdir or not os.path.isdir(shimdir):
            out.fail("Failed dual: tcc on Windows needs a winsock shim "
                     "(pass --tcc-shim DIR or set ORBIT_TCC_SHIM).")
            return 2
        if shim_header(shimdir) is None:
            out.fail("Failed dual: shim dir %s has neither tccenv.h nor "
                     "tcc_toolchain.h." % shimdir)
            return 2

    compiler = args.compiler or _common.fixed_point(gcc)
    if not compiler or not os.path.isfile(compiler):
        out.fail("Failed dual: no fixed-point compiler (pass --compiler PATH).")
        return 2

    suite_dirs = args.dir or [suite.SUITE,
                              os.path.join(ROOT, "tests", "std")]
    tests, collected = collect_tests(suite_dirs)
    if tests is None:
        out.fail("Failed dual: %s" % collected)
        return 1
    plans, skipped, excluded = collected
    if not plans:
        out.fail("Failed dual: no tests found")
        return 1

    if args.work:
        work = os.path.abspath(args.work)
        os.makedirs(work, exist_ok=True)
    else:
        work = tempfile.mkdtemp(prefix="orbit_dual_")
    if not args.keep and not args.work:
        import atexit
        import shutil as _sh
        atexit.register(lambda: _sh.rmtree(work, ignore_errors=True))

    workshim = os.path.join(work, "tcc_shim")
    os.makedirs(workshim, exist_ok=True)
    with open(os.path.join(workshim, "tcc_dual.h"), "w",
              encoding="utf-8", newline="\n") as fh:
        fh.write(TCC_DUAL_HEADER)
    tcc_extra_flags = "" if substitute else tcc_extra(shimdir, workshim)

    out.say("Dual judge: %d tests x (gcc=%s, tcc=%s)%s" %
            (len(plans), gcc, tcc,
             " [SUBSTITUTE: same driver twice]" if substitute else ""))
    out.say("Compiler: %s" % compiler)
    t0 = time.monotonic()
    ctx = {"gcc": gcc, "tcc": tcc, "compiler": compiler,
           "timeout": args.timeout, "work": work,
           "tcc_extra": tcc_extra_flags, "lock": threading.Lock(),
           "arm_secs": {"gcc": 0.0, "tcc": 0.0}}
    workers = args.workers or min(8, os.cpu_count() or 1)
    with ThreadPoolExecutor(max_workers=workers) as pool:
        results = list(pool.map(lambda p: run_dual_one(p, ctx), plans))

    ok = 0
    failed = []
    disagreements = []
    ratchets = []
    for row in results:
        name, kind, *rest = row
        plan = next(p for p in plans if p[1] == name)
        _, _, expected, ratchet_ref = plan
        if kind == "timeout-build":
            failed.append(name)
            out.fail("Failed %s: timed out building (%s arm)" % (name, rest[0]))
        elif kind == "timeout-run":
            failed.append(name)
            out.fail("Failed %s: timed out running (%s arm)" % (name, rest[0]))
        elif kind == "nobuild":
            tag, tail, build_rc = rest
            failed.append(name)
            out.fail("Failed %s: did not build under %s (rc=%s)" %
                     (name, tag, build_rc))
            for line in tail.splitlines():
                print("  " + line, file=sys.stderr)
        elif kind == "disagree":
            desc, gcc_probe, tcc_probe = rest
            failed.append(name)
            disagreements.append(name)
            out.fail("Failed %s: TOOLCHAIN SIGNAL -- %s" % (name, desc))
            for line in diff_detail(gcc_probe[1], tcc_probe[1]):
                print(line, file=sys.stderr)
            print("  gcc exit=%d tcc exit=%d" %
                  (gcc_probe[0], tcc_probe[0]), file=sys.stderr)
        elif kind == "agree":
            rc, _ = rest
            if expected is None:
                ref = (" " + ratchet_ref) if ratchet_ref else ""
                if rc != 0:
                    ok += 1
                    ratchets.append(name)
                    out.say("Testing %s ... exit %d, still red as declared "
                            "(known-failing:%s)" % (name, rc, ref))
                else:
                    failed.append(name)
                    out.fail("Failed %s: known-failing but both toolchains "
                             "exit 0 -- delete the directive." % name)
            elif rc == expected:
                ok += 1
                out.say("Testing %s ... agree exit %d as expected" % (name, rc))
            else:
                failed.append(name)
                out.fail("Failed %s: both agree on exit %d, want %d" %
                         (name, rc, expected))
    for name, why in skipped:
        failed.append(name)
        out.fail("Failed %s: header declares both expect-exit and "
                 "known-failing -- pick one" % name)

    dt = time.monotonic() - t0
    total = len(plans)
    extra = "(%d known-failing, asserted still red)" % len(ratchets) \
        if ratchets else ""
    if excluded:
        extra += (" " if extra else "") + "(%d excluded: %s)" % (
            len(excluded), ", ".join(n for n, _ in excluded))
        for name, why in excluded:
            out.say("Excluded %s: %s (gcc suite covers it)" % (name, why))
    if disagreements:
        extra += (" " if extra else "") + \
            "(%d toolchain SIGNALS: %s)" % (len(disagreements),
                                            ", ".join(disagreements[:10]))
    out.finish("dual", ok, total, extra=extra)
    out.say("Dual wall time: %.1fs over %d tests%s" %
            (dt, total, " (substitute mode)" if substitute else ""))
    out.say("Arm build+run totals: gcc=%.1fs tcc=%.1fs (summed over tests, "
            "%d workers; not a benchmark, just process evidence)" %
            (ctx["arm_secs"]["gcc"], ctx["arm_secs"]["tcc"], workers))
    if failed:
        payload = ", ".join(failed).replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")[:1500]
        out.fail("Failed: " + ", ".join(failed))
        out.ci_error("[orbit-dual] failed: %s" % payload)
    return 0 if not failed else 1


if __name__ == "__main__":
    raise SystemExit(main())
